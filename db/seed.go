// SeedData inserts initial alimentos and platillos if the DB is empty.
func SeedData(db *sql.DB) error {
	var count int
	db.QueryRow("SELECT COUNT(*) FROM alimentos").Scan(&count)
	if count > 0 {
		return nil
	}

	if err := seedAlimentos(db); err != nil {
		return err
	}
	if err := seedPlatillos(db); err != nil {
		return err
	}
	if err := seedVariantes(db); err != nil {
		return err
	}
	if err := seedIngredientes(db); err != nil {
		return err
	}
	return nil
}

